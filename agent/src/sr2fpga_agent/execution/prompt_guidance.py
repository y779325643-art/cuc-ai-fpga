"""Versioned, task-independent tool guidance shared by every model stage."""

MODEL_GUIDANCE_VERSION = "pc21-public-guidance-v2"

COMMON_MODEL_GUIDANCE = (
    "Public guidance [" + MODEL_GUIDANCE_VERSION + "]. "
    "The PC structure rules below apply only when a PC design is requested. "
    "Direct stages need not produce a PC; return the artifact requested by the stage. "
    "No task-specific module decomposition is prescribed.\n\n"
    "Tool compatibility guidance. "
    "Candidate RTL is parsed and synthesized with the native Yosys frontend using "
    "read_verilog -sv -noautowire; this frontend supports a SystemVerilog subset, "
    "not the full language. Simulation uses Icarus Verilog with iverilog -g2012 and vvp. "
    "Write portable synthesizable RTL accepted by both tools. Avoid unpacked parameter "
    "or localparam arrays and array assignment patterns. Express constant tables using "
    "case statements, functions with scalar arguments, or packed constants and explicit selection. "
    "Declare every signal explicitly. For combinational functions, pass every changing data "
    "dependency as an explicit function argument, or compute the expression in always_comb. "
    "A function used by a continuous assignment must not depend on changing module globals "
    "that are absent from its arguments. Preserve the public arithmetic and transaction obligations.\n\n"
    "PC names have three separate namespaces. Logical ports are keys in a module's "
    "signature.ports. Tensor descriptor IDs are keys in signature.tensor_contracts, "
    "selected by a port's payload.contract (kind=tensor_beat). Physical RTL wires "
    "are named by the ABI. For example, logical port rx may use descriptor PacketTensor "
    "and physical wires rx_data/rx_valid/rx_ready. In tensor_rules, buffer_rules and "
    "net endpoints, use logical port rx, not PacketTensor or rx_data. "
    "The public_interface_index, when supplied, explains only the requirement entry "
    "boundary; the original public boundary remains authoritative. Internal modules "
    "use their own local signature names.\n\n"
    "A behavioral module's implementation.tensor_rules must cover every tensor port "
    "exactly once as a main relation. Use logical input/output ports with their declared "
    "directions and one compatible bound domain. A compute relation accepts multiple "
    "inputs and outputs; it may cover the complete computation at that module boundary. "
    "Do not list the same port again for each internal operator. compute declares an "
    "obligation; it does not infer an algorithm. Use only the registered finite relation "
    "kinds and their required fields. Do not add unused tensor descriptors.\n\n"
    "State declarations belong in a behavioral module's implementation.states, not in "
    "signature.states. A state requires a consuming rising-edge domain; a combinational "
    "module cannot declare state or consume clock/reset. Tensor FIFO state additionally "
    "requires an implementation.buffer_rules binding to a local input port and a local "
    "output port. Both ports and the FIFO element_type must carry the identical complete "
    "tensor beat in the same bound domain. capacity_unit is beats. A buffer binding is "
    "additional to the ports' main tensor relation, not another main relation. It describes "
    "that input-to-output buffer only; an arbitrary FIFO of internally computed results "
    "is not automatically expressible by this binding. Do not invent internal port names "
    "or omit a required binding to make a declaration pass.\n\n"
    "Structural nets connect self or an immediate child through logical port names. "
    "Every receiver needs exactly one driver. Streams are point-to-point, and direct "
    "connections require matching complete types/encodings and bound domains, not just "
    "matching packed widths. Local descriptor IDs may differ when their resolved "
    "descriptors match. Conversion, buffering and stream fanout are not inserted "
    "automatically. The entry signature uses source=requirement_boundary; internal "
    "declared signatures, instance parameter/domain bindings and required public-fact "
    "mappings must follow the supplied schema and public requirements.\n\n"
    "The capability profile is a finite implementation boundary: respect its instance, "
    "hierarchy, width, tensor-size, clock-domain and reset limits. Tensor shapes are "
    "configuration-local; unsupported runtime-variable, sparse or ragged shapes do not "
    "become supported by adding fields. Static checks establish listed declaration "
    "consistency only. They do not prove actual arithmetic/layout, transaction identity, "
    "backpressure/reset behavior, state implementation, liveness, timing or resources. "
    "Declarations do not generate these behaviors; implement the public obligations in RTL."
)
